// RainViewer radar pixel colours, converted to a numeric grid outside the sandbox.
// The region is georeferenced by Web Mercator at ingestion and drawn in SVG here.
// There are no external images, map tiles, scripts or network requests in this UI.
type Frame = { capturedAt: number; grid: string; palette: string[]; size: number; bounds: number[] };
type Point = { x: number; y: number };

export default function RadarLayer({ frame, project }: { frame: Frame | undefined; project: (lon: number, lat: number) => Point }) {
  if (!frame || frame.size !== 80 || !Array.isArray(frame.palette) || frame.palette.length > 30 || frame.bounds?.length !== 4) return null;
  const [west, south, east, north] = frame.bounds;
  if (Math.abs(west - 152) > 0.001 || Math.abs(south + 30.2) > 0.001 ||
      Math.abs(east - 154.2) > 0.001 || Math.abs(north + 27.7) > 0.001) return null;
  let cells: string;
  try { cells = atob(frame.grid); } catch { return null; }
  if (cells.length !== 6400) return null;
  const size = 80;
  const corner = project(west, north);
  const other = project(east, south);
  const w = (other.x - corner.x) / size, h = (other.y - corner.y) / size;
  // One rect per horizontal run of the same colour, not per cell. Widespread rain can
  // fill all 6,400 cells, and the animation redraws every 0.8 s.
  const visible = [];
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size;) {
      const index = cells.charCodeAt(row * size + col);
      let end = col + 1;
      while (end < size && cells.charCodeAt(row * size + end) === index) end++;
      const colour = index === 0 ? undefined : frame.palette[index - 1];
      if (colour) {
        visible.push(<rect key={row * size + col} x={corner.x + col * w} y={corner.y + row * h}
          width={(end - col) * w + 0.2} height={h + 0.2} fill={'#' + colour} opacity={0.72} />);
      }
      col = end;
    }
  }
  return <g pointerEvents="none" aria-label="RainViewer radar reflectivity overlay, generated by Aeolus">{visible}</g>;
}
